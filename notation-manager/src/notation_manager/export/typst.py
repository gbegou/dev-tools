"""Export to Typst: one variable (or function) per notation, and a nomenclature.

The exported file is imported where the notations are used::

    #import "notations.typ": *
    $velocity = norm(x)$
    #notation-nomenclature()

The helpers have hyphenated names (``notation-groups``, ``notation-nomenclature``), which no
notation name can take.
"""

import re

from notation_manager.model import Group, Notation, NotationSet

__all__ = ["MINIMUM_TYPST_VERSION", "to_typst"]

MINIMUM_TYPST_VERSION = "0.13"
"""The oldest Typst version that compiles the export (it uses the ``std`` module)."""

_PLACEHOLDER = re.compile(r"#(\d)")


def _string(text: str) -> str:
    """Return ``text`` as a Typst string literal."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def _definition(notation: Notation) -> str:
    if not notation.arguments:
        return f"#let {notation.name} = ${notation.symbol.typst}$"
    parameters = ", ".join(f"arg{index}" for index in range(1, notation.arguments + 1))
    body = _PLACEHOLDER.sub(r"#(arg\1)", notation.symbol.typst)
    # An anonymous function does not see its own name, so a notation can use the builtin it
    # shadows (``#let norm = (arg1) => $norm(#(arg1))$``) without recursing.
    return f"#let {notation.name} = ({parameters}) => ${body}$"


def _entry(notation: Notation) -> str:
    symbol = notation.name
    if notation.arguments:
        symbol += "(" + ", ".join(["std.sym.dot.c"] * notation.arguments) + ")"
    units = f"[{notation.units.typst}]" if notation.units.typst else "none"
    return (
        f"      (name: {_string(notation.name)}, symbol: {symbol}, "
        f"description: [{notation.description.typst}], units: {units}),"
    )


def _group(group: Group | None, members: list[Notation]) -> list[str]:
    key = "none" if group is None else _string(group.key)
    title = "none" if group is None else f"[{group.title.typst}]"
    return [
        "  (",
        f"    key: {key},",
        f"    title: {title},",
        "    entries: (",
        *(_entry(notation) for notation in members),
        "    ),",
        "  ),",
    ]


_NOMENCLATURE = """\
/// The nomenclature: a heading, then a grid of symbols, descriptions and units, with a row
/// for the title of each group.
#let notation-nomenclature(
  title: [Nomenclature],
  columns: (auto, 1fr, auto),
  align: (left, left, right),
  column-gutter: 1em,
  row-gutter: 0.8em,
  group-title: title => std.strong(title),
) = {
  if title != none { std.heading(numbering: none, title) }
  let cells = ()
  for group in notation-groups {
    if group.title != none {
      cells.push(std.grid.cell(colspan: columns.len(), group-title(group.title)))
    }
    for entry in group.entries {
      cells += (entry.symbol, entry.description, entry.units)
    }
  }
  std.grid(
    columns: columns,
    align: align,
    column-gutter: column-gutter,
    row-gutter: row-gutter,
    ..cells,
  )
}
"""


def to_typst(notations: NotationSet, *, source: str | None = None) -> str:
    """Return the Typst file of ``notations``.

    Each notation becomes a variable (``#let velocity = $bold(u)$``), or a function of its
    arguments, whose placeholders ``#1``... become the parameters ``arg1``...
    (``#let norm = (arg1) => $lr(|| #(arg1) ||)$``). ``notation-groups`` holds the nomenclature in
    order (ungrouped notations first, under a ``none`` title), and ``notation-nomenclature()``
    prints it; the arguments of a function are shown as ``dot.c``.

    Parameters
    ----------
    notations
        The notations.
    source
        The notation file, named in the header comment.
    """
    origin = f" from {source}" if source else ""
    lines = [
        f"// Generated by notation-manager{origin}: edit the notation file, not this one.",
        f"// Typst {MINIMUM_TYPST_VERSION} or later. Use:",
        '//   #import "<this file>": *',
        "//   $velocity$ in math, #notation-nomenclature() where the nomenclature goes.",
        "",
        "// Notations",
    ]
    lines.extend(_definition(notation) for notation in notations)
    lines.extend(["", "// Nomenclature", "#let notation-groups = ("])
    for group, members in notations.nomenclature():
        lines.extend(_group(group, members))
    lines.extend([")", "", _NOMENCLATURE.rstrip("\n")])
    return "\n".join(lines) + "\n"
