r"""Export to LaTeX: one command per notation, and the nomenclature for the nomencl package.

The exported file is input in the preamble, after ``\usepackage{nomencl}`` and
``\makenomenclature``; ``\notationnomenclature`` then declares every entry, where the
document calls it (before ``\printnomenclature``)::

    \usepackage{nomencl}
    \makenomenclature
    \input{notations}
    ...
    \notationnomenclature
    \printnomenclature
"""

import string
from typing import Literal

from notation_manager.export._common import resolve_language
from notation_manager.model import Notation, NotationError, NotationSet
from notation_manager.typing import Language

__all__ = ["MAX_GROUPS", "NOMENCLATURE_COMMAND", "Definition", "to_latex"]

type Definition = Literal["newcommand", "renewcommand", "providecommand", "DeclareRobustCommand"]
"""The LaTeX command that defines each notation."""

NOMENCLATURE_COMMAND = "notationnomenclature"
"""The command that declares the nomenclature entries."""

MAX_GROUPS = len(string.ascii_uppercase) - 1
"""The most groups with notations that a LaTeX nomenclature tells apart.

nomencl tells groups apart by the first letter of the sort prefix, and ``A`` is for the
notations without a group.
"""

_GROUP_LETTERS = string.ascii_uppercase[1:]

_NOMGROUP = r"""\makeatletter
{titles}
\renewcommand{{\nomgroup}}[1]{{%
  \@ifundefined{{notation@group@#1}}{{}}{{\item[\bfseries\@nameuse{{notation@group@#1}}]}}}}
\makeatother"""


def _definition(notation: Notation, definition: Definition) -> str:
    arguments = f"[{notation.arguments}]" if notation.arguments else ""
    body = rf"\ensuremath{{{notation.symbol.latex}}}"
    return rf"\{definition}{{\{notation.name}}}{arguments}{{{body}}}"


def _group_title(letter: str, title: str) -> str:
    return rf"\@namedef{{notation@group@{letter}}}{{{title}}}"


def _entry(notation: Notation, prefix: str, language: Language, default: Language) -> str:
    call = rf"\{notation.name}" + r"{\cdot}" * notation.arguments
    description = notation.description.resolve(language, default).latex
    if notation.units.latex:
        description += rf"\nomunit{{{notation.units.latex}}}"
    return rf"  \nomenclature[{prefix}]{{${call}$}}{{{description}}}%"


def to_latex(
    notations: NotationSet,
    *,
    language: Language | None = None,
    source: str | None = None,
    definition: Definition = "newcommand",
) -> str:
    r"""Return the LaTeX file of ``notations``.

    Each notation becomes a command (``\newcommand{\velocity}{\ensuremath{\mathbf{u}}}``),
    usable in text and math. ``\notationnomenclature`` declares one ``\nomenclature`` entry
    per notation, with the units in ``\nomunit`` (defined when nomencl does not define it),
    and the arguments of a command shown as ``\cdot``. With groups, ``\nomgroup`` is redefined
    to print the group titles.

    Parameters
    ----------
    notations
        The notations.
    language
        The language of the descriptions and group titles: the default language of
        ``notations`` when ``None``. A missing translation falls back on the default language,
        with a warning in the log.
    source
        The notation file, named in the header comment.
    definition
        The command that defines each notation: ``newcommand`` (the default) fails on a name
        that LaTeX or a package already defines.

    Raises
    ------
    NotationError
        If more than :data:`~notation_manager.export.latex.MAX_GROUPS` groups have notations,
        or ``language`` is not declared.
    """
    language = resolve_language(notations, language)
    default = notations.default_language
    sections = notations.nomenclature()
    grouped = [group for group, _ in sections if group is not None]
    if len(grouped) > MAX_GROUPS:
        raise NotationError(
            f"latex: {len(grouped)} groups have notations, "
            + f"nomencl tells at most {MAX_GROUPS} apart"
        )
    origin = f" from {source}" if source else ""
    lines = [
        f"% Generated by notation-manager{origin}, in {language}: edit the notation file, not "
        + "this one.",
        r"% In the preamble, after \usepackage{nomencl} and \makenomenclature:",
        r"%   \input{<this file>}",
        r"% In the document, where the nomenclature goes:",
        rf"%   \{NOMENCLATURE_COMMAND} \printnomenclature",
        "",
        "% Notations",
        *(_definition(notation, definition) for notation in notations),
        "",
        "% Nomenclature",
        r"\providecommand{\nomunit}[1]{\renewcommand{\nomentryend}{\hspace*{\fill}#1}}",
    ]
    if grouped:
        titles = "\n".join(
            _group_title(letter, group.title.resolve(language, default).latex)
            for letter, group in zip(_GROUP_LETTERS, grouped, strict=False)
        )
        lines.append(_NOMGROUP.format(titles=titles))
    lines.append(rf"\newcommand{{\{NOMENCLATURE_COMMAND}}}{{%")
    letters = iter(_GROUP_LETTERS)
    for group, members in sections:
        # The prefix sorts the entries: the group letter, then the sort key.
        letter = ("A" if group is None else next(letters)) if grouped else ""
        lines.extend(
            _entry(notation, letter + notation.sort_key[0], language, default)
            for notation in members
        )
    lines.append("}")
    return "\n".join(lines) + "\n"
