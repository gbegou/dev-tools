"""Typst export: the generated code, and a document compiled with it (when typst is installed)."""

import importlib.util
import shutil
from pathlib import Path

import pytest

from anatole import (
    Acronym,
    Notation,
    NotationError,
    NotationSet,
    Rendered,
    Translated,
    to_typst,
)


def test_variables_and_functions(small: NotationSet) -> None:
    text = to_typst(small)
    assert "#let velocity = $bold(u)$" in text
    assert "#let norm = (arg1) => $norm(#(arg1))$" in text


def test_functions_of_several_arguments() -> None:
    notation = Notation(
        "inner",
        Rendered("#1 #2", "angle.l #1, #2 angle.r"),
        Translated({"en": "Inner"}),
        arguments=2,
    )
    text = to_typst(NotationSet([notation]))
    assert "#let inner = (arg1, arg2) => $angle.l #(arg1), #(arg2) angle.r$" in text
    assert "symbol: inner(std.sym.dot.c, std.sym.dot.c)" in text


def test_groups_in_nomenclature_order(small: NotationSet) -> None:
    text = to_typst(small)
    keys = [line.strip() for line in text.splitlines() if line.strip().startswith("key:")]
    assert keys == ["key: none,", 'key: "latin",', 'key: "greek",']
    assert '(name: "velocity", symbol: velocity, description: [Velocity], units: [m/s]),' in text
    assert '(name: "time", symbol: time, description: [Time], units: none),' in text


def test_source_in_the_header(small: NotationSet) -> None:
    assert to_typst(small, source="notations.toml").startswith(
        "// Generated by anatole from notations.toml, in en"
    )


def test_language(small: NotationSet) -> None:
    text = to_typst(small, language="fr")
    assert "title: [Grec]," in text
    assert "description: [Vitesse]" in text
    assert "description: [Density]" in text  # no French translation: English
    with pytest.raises(NotationError, match="language 'de' is not declared"):
        _ = to_typst(small, language="de")


def test_styles_references_and_order(example: NotationSet) -> None:
    text = to_typst(example)
    assert "#let vect = (arg1) => $bold(#(arg1))$" in text
    assert "#let velocity = $vect(u)$" in text
    assert '#let redelta = $italic("Re")_(#blthickness)$' in text
    assert "description: [Reynolds number based on #blthickness]" in text
    lets = [line.split(" =")[0] for line in text.splitlines() if line.startswith("#let ")]
    assert lets.index("#let vect") < lets.index("#let velocity")
    assert lets.index("#let blthickness") < lets.index("#let redelta")


def test_reference_ends_before_a_letter() -> None:
    notations = NotationSet(
        [
            Notation("blthickness", Rendered.both("delta"), Translated({"en": "x"})),
            Notation("ratio", Rendered.both("@{blthickness}x"), Translated({"en": "x"})),
        ]
    )
    assert "#let ratio = $#blthickness;x$" in to_typst(notations)


def test_acronyms(example: NotationSet) -> None:
    text = to_typst(example, language="fr")
    assert '#let cfd = anatole-acronym("cfd", [MFN], [mécanique des fluides numérique], ' in text
    assert '#let wrt = anatole-acronym("wrt", [p.r.à], [par rapport à], expand: false)' in text
    assert "#let acronym-groups = (" in text


typst_available = importlib.util.find_spec("typst") is not None

EXAMPLES = Path(__file__).resolve().parent.parent / "examples"


@pytest.mark.skipif(not typst_available, reason="needs the typst package")
@pytest.mark.parametrize("language", ["en", "fr"])
def test_document_compiles(tmp_path: Path, example: NotationSet, language: str) -> None:
    import typst

    text = to_typst(example, language=language)
    _ = (tmp_path / "notations.typ").write_text(text, encoding="utf-8")
    _ = shutil.copy(EXAMPLES / "document.typ", tmp_path)
    pdf = typst.compile(str(tmp_path / "document.typ"))
    assert pdf.startswith(b"%PDF")


@pytest.mark.skipif(not typst_available, reason="needs the typst package")
def test_notations_shadowing_builtins_compile(tmp_path: Path) -> None:
    """Notations named like the builtins the nomenclature uses do not break it."""
    import typst

    notations = NotationSet(
        Notation(name, Rendered.both("x"), Translated({"en": name}))
        for name in ("grid", "heading", "strong", "cells", "group", "title", "entry", "columns")
    )
    _ = (tmp_path / "notations.typ").write_text(to_typst(notations), encoding="utf-8")
    _ = (tmp_path / "document.typ").write_text(
        '#import "notations.typ": *\n$grid + title$\n#notation-nomenclature()\n',
        encoding="utf-8",
    )
    assert typst.compile(str(tmp_path / "document.typ")).startswith(b"%PDF")


@pytest.mark.skipif(not typst_available, reason="needs the typst package")
def test_notations_using_the_builtin_they_shadow_compile(tmp_path: Path) -> None:
    """``norm`` defined with the builtin ``norm`` does not call itself."""
    import typst

    notations = NotationSet(
        [
            Notation("norm", Rendered.both("norm(#1)"), Translated({"en": "Norm"}), arguments=1),
            Notation("sum", Rendered.both("sum"), Translated({"en": "Sum"})),
        ]
    )
    _ = (tmp_path / "notations.typ").write_text(to_typst(notations), encoding="utf-8")
    _ = (tmp_path / "document.typ").write_text(
        '#import "notations.typ": *\n$norm(x) + sum$\n#notation-nomenclature()\n',
        encoding="utf-8",
    )
    assert typst.compile(str(tmp_path / "document.typ")).startswith(b"%PDF")


FIRST_USE = """\
#import "notations.typ": *
#cfd, #cfd, #wrt.
#context assert.eq(anatole-acronyms-used.final(), ("cfd", "wrt"))
"""


@pytest.mark.skipif(not typst_available, reason="needs the typst package")
@pytest.mark.skipif(shutil.which("pdftotext") is None, reason="needs pdftotext")
def test_acronyms_expand_at_first_use(tmp_path: Path) -> None:
    import subprocess

    import typst

    notations = NotationSet(
        [
            Acronym("cfd", Translated({"en": "CFD"}), Translated({"en": "fluid dynamics"})),
            Acronym(
                "wrt",
                Translated({"en": "w.r.t."}),
                Translated({"en": "with respect to"}),
                abbreviation=True,
            ),
        ]
    )
    _ = (tmp_path / "notations.typ").write_text(to_typst(notations), encoding="utf-8")
    _ = (tmp_path / "document.typ").write_text(FIRST_USE, encoding="utf-8")
    _ = (tmp_path / "document.pdf").write_bytes(typst.compile(str(tmp_path / "document.typ")))
    text = subprocess.run(
        ["pdftotext", str(tmp_path / "document.pdf"), "-"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    assert "fluid dynamics (CFD), CFD, w.r.t.." in " ".join(text.split())
